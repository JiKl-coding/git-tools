param([string]$ScriptDir)

# Installation and configuration of git-tools.sh (run via GitToolsSetup.cmd)
$ErrorActionPreference = 'Stop'
[Console]::OutputEncoding = [Text.Encoding]::UTF8

if (-not $ScriptDir) { $ScriptDir = $PSScriptRoot }
$ScriptDir = $ScriptDir.TrimEnd('\', '/')

$ZdrojSkript = Join-Path $ScriptDir 'git-tools.sh'
$DomovDir    = if ($env:HOME) { $env:HOME } else { $env:USERPROFILE }
$NazevSkriptu = 'git-tools.sh'
$VychoziConf = 'J:/config/git-tools.conf'

$VychoziHodnoty = [ordered]@{
    USER_PREFIX  = 'user/unknown/'
    ENV_BRANCHES = 'main dev acc int work'
    DEFAULT_BASE = 'main'
    DIFF_LOG_DIR = 'j:/temp'
    LEGACY_DIR   = ''
}
$PopisKlicu = @{
    USER_PREFIX  = 'Prefix of user branches (e.g. user/jikl/)'
    ENV_BRANCHES = 'Protected env branches (space-separated)'
    DEFAULT_BASE = 'Default base branch'
    DIFF_LOG_DIR = 'Folder for dif --log'
    LEGACY_DIR   = 'Prefix for files without a path (dif-file, com), empty = no prefix'
}

# alias -> git-tools.sh command
$Aliasy = [ordered]@{}
foreach ($a in 'new','sw','del','com','sync','merg','reb','reb-ai','reb-ac','done','gone','up','dif','dif-file','st','br','cp','ver') { $Aliasy[$a] = $a }
$Aliasy['h'] = 'help'

$RegexConfRadek = '(?m)^GITTOOLS_CONFIG_DEFAULT=.*$'

# =========================
# Helper functions
# =========================
function Write-UnixText([string]$Cesta, [string]$Text) {
    $dir = Split-Path -Parent $Cesta
    if ($dir -and -not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
    # bash cannot handle CRLF or BOM
    $Text = $Text -replace "`r`n", "`n"
    [IO.File]::WriteAllText($Cesta, $Text, (New-Object Text.UTF8Encoding $false))
}

function Read-Text([string]$Cesta) {
    [IO.File]::ReadAllText($Cesta, [Text.Encoding]::UTF8)
}

function Get-InstalovanySkript {
    Join-Path $script:InstalDir $NazevSkriptu
}

function Get-ConfZeSkriptu([string]$Skript) {
    if (-not (Test-Path -LiteralPath $Skript)) { return $null }
    $m = [regex]::Match((Read-Text $Skript), '(?m)^GITTOOLS_CONFIG_DEFAULT="?([^"\r\n]*)"?')
    if ($m.Success) { return $m.Groups[1].Value }
    return $null
}

function Read-Conf([string]$Cesta) {
    $h = [ordered]@{}
    foreach ($k in $VychoziHodnoty.Keys) { $h[$k] = $null }
    if (-not (Test-Path -LiteralPath $Cesta)) { return $h }
    foreach ($radek in (Read-Text $Cesta) -split "`n") {
        $m = [regex]::Match($radek.TrimEnd("`r"), '^\s*([A-Z_]+)\s*=\s*(.*?)\s*$')
        if (-not $m.Success) { continue }
        $hodnota = $m.Groups[2].Value
        if ($hodnota -match "^'(.*)'$") { $hodnota = $Matches[1] -replace "'\\''", "'" }
        elseif ($hodnota -match '^"(.*)"$') { $hodnota = $Matches[1] }
        $h[$m.Groups[1].Value] = $hodnota
    }
    return $h
}

function Write-Conf([string]$Cesta, $Hodnoty) {
    $sb = New-Object Text.StringBuilder
    [void]$sb.AppendLine('# git-tools.conf - loaded by git-tools.sh (bash syntax)')
    [void]$sb.AppendLine("# Generated by GitToolsSetup $(Get-Date -Format 'yyyy-MM-dd HH:mm')")
    foreach ($k in $VychoziHodnoty.Keys) {
        $v = [string]$Hodnoty[$k]
        [void]$sb.AppendLine("$k='" + ($v -replace "'", "'\''") + "'")
    }
    Write-UnixText $Cesta $sb.ToString()
}

function Read-Hodnota([string]$Popis, [string]$Aktualni) {
    $odpoved = Read-Host "$Popis [$Aktualni] (Enter = keep, '-' = empty)"
    if ($odpoved -eq '') { return $Aktualni }
    if ($odpoved -eq '-') { return '' }
    return $odpoved
}

function Read-AnoNe([string]$Otazka) {
    $odpoved = Read-Host "$Otazka [y/N]"
    return ($odpoved -match '^(y|yes|a|ano)$')
}

function Edit-Hodnoty($Hodnoty) {
    $nove = [ordered]@{}
    foreach ($k in $VychoziHodnoty.Keys) {
        $akt = if ($null -ne $Hodnoty[$k]) { [string]$Hodnoty[$k] } else { $VychoziHodnoty[$k] }
        $nove[$k] = Read-Hodnota "$k - $($PopisKlicu[$k])" $akt
    }
    return $nove
}

function Set-ConfVeSkriptu([string]$Skript, [string]$ConfCesta) {
    $text = Read-Text $Skript
    if ($text -notmatch $RegexConfRadek) { throw "Line GITTOOLS_CONFIG_DEFAULT= is missing in $Skript" }
    $text = [regex]::Replace($text, $RegexConfRadek, "GITTOOLS_CONFIG_DEFAULT=`"$ConfCesta`"")
    Write-UnixText $Skript $text
}

function Get-AliasPrikaz([string]$Skript, [string]$Prikaz) {
    $dir = (Split-Path -Parent $Skript).TrimEnd('\', '/')
    if ($dir -ieq $DomovDir.TrimEnd('\', '/')) {
        $cesta = '$HOME/' + $NazevSkriptu
    } else {
        $cesta = $Skript -replace '\\', '/'
    }
    return "!$cesta $Prikaz"
}

function Get-GitAlias([string]$Nazev) {
    $v = & git config --global --get "alias.$Nazev"
    if ($LASTEXITCODE -ne 0) { return $null }
    return $v
}

# =========================
# Menu actions
# =========================
function Show-Nastaveni {
    $skript = Get-InstalovanySkript
    $gitconfig = Join-Path $DomovDir '.gitconfig'
    Write-Host ''
    Write-Host '--- Locations ---'
    Write-Host "Source script:        $ZdrojSkript"
    Write-Host ("Installed script:     $skript " + $(if (Test-Path -LiteralPath $skript) { '(exists)' } else { '(DOES NOT EXIST)' }))
    Write-Host ("Conf in script:       " + $(if ($c = Get-ConfZeSkriptu $skript) { $c } else { '-' }))
    Write-Host ("Conf (current):       $script:ConfCesta " + $(if (Test-Path -LiteralPath $script:ConfCesta) { '(exists)' } else { '(DOES NOT EXIST)' }))
    Write-Host ("Env GITTOOLS_CONFIG:  " + $(if ($env:GITTOOLS_CONFIG) { $env:GITTOOLS_CONFIG } else { '-' }))
    Write-Host ("Global .gitconfig:    $gitconfig " + $(if (Test-Path -LiteralPath $gitconfig) { '(exists)' } else { '(DOES NOT EXIST)' }))

    Write-Host ''
    Write-Host '--- Values in git-tools.conf ---'
    $h = Read-Conf $script:ConfCesta
    foreach ($k in $VychoziHodnoty.Keys) {
        if ($null -ne $h[$k]) { $zobraz = "'$($h[$k])'" } else { $zobraz = "(not in conf, fallback '$($VychoziHodnoty[$k])')" }
        Write-Host ('{0,-13} = {1}' -f $k, $zobraz)
    }

    Write-Host ''
    Write-Host '--- Aliases in .gitconfig ---'
    foreach ($a in $Aliasy.Keys) {
        $v = Get-GitAlias $a
        if ($null -eq $v) { $v = '(not set)' }
        Write-Host ('{0,-9} = {1}' -f $a, $v)
    }
}

function Edit-Nastaveni {
    if (-not (Test-Path -LiteralPath $script:ConfCesta)) {
        Write-Host "Conf $script:ConfCesta does not exist - use option 3 (create)."
        return
    }
    $nove = Edit-Hodnoty (Read-Conf $script:ConfCesta)
    Write-Conf $script:ConfCesta $nove
    Write-Host "Saved: $script:ConfCesta"
}

function New-Conf {
    $cesta = Read-Hodnota 'Path to git-tools.conf' $script:ConfCesta
    if (-not $cesta) { Write-Host 'Path must not be empty.'; return }
    $cesta = $cesta -replace '\\', '/'
    $vychozi = $VychoziHodnoty
    if (Test-Path -LiteralPath $cesta) {
        if (-not (Read-AnoNe "File $cesta already exists. Overwrite?")) { return }
        $vychozi = Read-Conf $cesta
    }
    $nove = Edit-Hodnoty $vychozi
    Write-Conf $cesta $nove
    $script:ConfCesta = $cesta
    Write-Host "Created: $cesta"

    $skript = Get-InstalovanySkript
    if (Test-Path -LiteralPath $skript) {
        Set-ConfVeSkriptu $skript $cesta
        Write-Host "Conf path set in $skript"
    } else {
        Write-Host 'git-tools.sh is not installed yet - the path will be set during installation (option 4).'
    }
}

function Install-Skript {
    if (-not (Test-Path -LiteralPath $ZdrojSkript)) { Write-Host "Source $ZdrojSkript does not exist."; return }
    $dir = Read-Hodnota "Target folder (global .gitconfig is in $DomovDir)" $script:InstalDir
    if (-not $dir) { Write-Host 'Folder must not be empty.'; return }
    $cil = Join-Path $dir $NazevSkriptu
    if ((Test-Path -LiteralPath $cil) -and -not (Read-AnoNe "$cil already exists. Overwrite?")) { return }

    $conf = Read-Hodnota 'Path to git-tools.conf that the script will load' $script:ConfCesta
    $conf = $conf -replace '\\', '/'
    if (-not (Test-Path -LiteralPath $conf)) { Write-Host "WARNING: $conf does not exist - the script will use fallback values (create it with option 3)." }

    $text = Read-Text $ZdrojSkript
    if ($text -notmatch $RegexConfRadek) { throw "Line GITTOOLS_CONFIG_DEFAULT= is missing in the source" }
    $text = [regex]::Replace($text, $RegexConfRadek, "GITTOOLS_CONFIG_DEFAULT=`"$conf`"")
    Write-UnixText $cil $text

    $script:InstalDir = $dir
    $script:ConfCesta = $conf
    Write-Host "Installed: $cil (conf: $conf)"
}

function Set-Aliasy {
    $skript = Get-InstalovanySkript
    if (-not (Test-Path -LiteralPath $skript)) { Write-Host "$skript does not exist - install first (option 4)."; return }
    if ($skript -match '\s') { Write-Host "Path $skript contains a space - aliases cannot be written, install elsewhere."; return }

    Write-Host ''
    $zmeny = [ordered]@{}
    foreach ($a in $Aliasy.Keys) {
        $novy = Get-AliasPrikaz $skript $Aliasy[$a]
        $stary = Get-GitAlias $a
        if ($stary -eq $novy) { continue }
        $zmeny[$a] = $novy
        if ($null -eq $stary) { Write-Host ('  + {0,-9} = {1}' -f $a, $novy) }
        else { Write-Host ('  ~ {0,-9} = {1}   (was: {2})' -f $a, $novy, $stary) }
    }
    if ($zmeny.Count -eq 0) { Write-Host 'All aliases are already set.'; return }
    if (-not (Read-AnoNe 'Write these aliases to the global .gitconfig?')) { return }

    foreach ($a in $zmeny.Keys) {
        & git config --global "alias.$a" $zmeny[$a]
        if ($LASTEXITCODE -ne 0) { Write-Host "ERROR writing alias $a" }
    }
    Write-Host "Aliases written: $($zmeny.Count)"
}

# =========================
# Main loop
# =========================
if (-not (Get-Command git -ErrorAction SilentlyContinue)) { Write-Host 'git is not in PATH.'; exit 1 }

$script:InstalDir = $DomovDir
$script:ConfCesta = Get-ConfZeSkriptu (Get-InstalovanySkript)
if (-not $script:ConfCesta) { $script:ConfCesta = Get-ConfZeSkriptu $ZdrojSkript }
if (-not $script:ConfCesta) { $script:ConfCesta = $VychoziConf }

while ($true) {
    Write-Host ''
    Write-Host '===== git-tools setup ====='
    Write-Host '1) Show current settings'
    Write-Host '2) Change settings (git-tools.conf)'
    Write-Host '3) Create git-tools.conf and set its path in git-tools.sh'
    Write-Host '4) Install git-tools.sh (next to .gitconfig)'
    Write-Host '5) Write aliases to .gitconfig'
    Write-Host '0) Exit'
    $volba = Read-Host 'Choice'
    try {
        switch ($volba) {
            '1' { Show-Nastaveni }
            '2' { Edit-Nastaveni }
            '3' { New-Conf }
            '4' { Install-Skript }
            '5' { Set-Aliasy }
            '0' { return }
            default { Write-Host 'Invalid choice.' }
        }
    } catch {
        Write-Host "ERROR: $($_.Exception.Message)"
    }
}
